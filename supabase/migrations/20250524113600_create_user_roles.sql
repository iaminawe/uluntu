DROP TABLE IF EXISTS public.user_roles CASCADE;
DROP TYPE IF EXISTS public.app_role CASCADE;

CREATE TYPE public.app_role AS ENUM (
  'authenticated',
  'group_member',
  'admin',
  'superadmin'
);

CREATE TABLE public.user_roles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
  role app_role NOT NULL,
  created_at timestamptz DEFAULT now() NOT NULL,
  CONSTRAINT user_roles_user_id_role_key UNIQUE (user_id, role) -- Ensures a user doesn't have the same role twice
);

-- Add comments to the table and columns
COMMENT ON TABLE public.user_roles IS 'Stores roles assigned to users.';
COMMENT ON COLUMN public.user_roles.user_id IS 'Foreign key to the users table in the auth schema.';
COMMENT ON COLUMN public.user_roles.role IS 'The role assigned to the user.';

-- Enable Row Level Security
ALTER TABLE public.user_roles ENABLE ROW LEVEL SECURITY;

-- Policies
CREATE POLICY "Users can view their own roles"
  ON public.user_roles FOR SELECT
  USING (auth.uid() = user_id);

-- Note on INSERT/UPDATE/DELETE policies for user_roles:
-- These operations, especially for assigning/revoking admin or other sensitive roles,
-- should typically be handled by trusted backend functions (SECURITY DEFINER)
-- or manual database operations by a superadmin.
-- Broad RLS policies for these actions on user_roles can easily lead to security vulnerabilities
-- or the "infinite recursion" error if not designed with extreme care.
-- The "infinite recursion" error you encountered was likely due to a policy
-- (perhaps for SELECT or a write operation) that re-queried user_roles itself
-- through a helper function or view.
-- Start with minimal policies and add more complex ones carefully, testing each one.

-- Optional: Indexes
CREATE INDEX idx_user_roles_user_id ON public.user_roles(user_id);
CREATE INDEX idx_user_roles_role ON public.user_roles(role);
