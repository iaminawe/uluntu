/**
 * @jest-environment jsdom
 */

import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import React from 'react';

// Import AI editor components
import BlockEditorWithAI from '@/components/BlockEditorWithAI';
import { AIService } from '@/lib/ai/services/aiService';
import { ContentTransformer } from '@/lib/ai/utils/contentTransformer';
import { ImageService } from '@/lib/ai/services/imageService';

// Mock AI services
jest.mock('@/lib/ai/services/aiService');
jest.mock('@/lib/ai/services/imageService');
jest.mock('@/lib/ai/utils/contentTransformer');

const mockAIService = AIService as jest.MockedClass<typeof AIService>;
const mockImageService = ImageService as jest.MockedClass<typeof ImageService>;
const mockContentTransformer = ContentTransformer as jest.MockedClass<typeof ContentTransformer>;

// Mock responses
const mockAIResponse = {
  content: '# AI Generated Content\n\nThis is a blog post generated by AI about technology trends.',
  images: [
    {
      url: 'https://images.unsplash.com/photo-tech-1',
      alt: 'Technology concept',
      attribution: 'Photo by Tech User on Unsplash'
    }
  ]
};

const mockBlockContent = [
  {
    type: 'heading',
    content: [{ type: 'text', text: 'AI Generated Content', styles: {} }]
  },
  {
    type: 'paragraph',
    content: [{ type: 'text', text: 'This is a blog post generated by AI about technology trends.', styles: {} }]
  },
  {
    type: 'image',
    props: {
      url: 'https://images.unsplash.com/photo-tech-1',
      alt: 'Technology concept',
      caption: 'Photo by Tech User on Unsplash'
    }
  }
];

// Test providers
const createTestProviders = () => {
  const queryClient = new QueryClient({
    defaultOptions: {
      queries: { retry: false },
      mutations: { retry: false },
    },
  });

  const TestProviders: React.FC<{ children: React.ReactNode }> = ({ children }) => (
    <QueryClientProvider client={queryClient}>
      {children}
    </QueryClientProvider>
  );

  return { TestProviders, queryClient };
};

describe('AI Editor Integration Tests', () => {
  beforeEach(() => {
    jest.clearAllMocks();
    
    // Setup default mocks
    mockAIService.prototype.generateContent = jest.fn().mockResolvedValue(mockAIResponse);
    mockImageService.prototype.searchImages = jest.fn().mockResolvedValue([]);
    mockContentTransformer.prototype.markdownToBlocks = jest.fn().mockReturnValue(mockBlockContent);
  });

  describe('AI Content Generation', () => {
    test('should generate blog post with AI command', async () => {
      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      const mockOnChange = jest.fn();

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent=""
            onChange={mockOnChange}
            placeholder="Start writing or use AI commands..."
          />
        </TestProviders>
      );

      // Type AI command
      const editor = screen.getByRole('textbox');
      await user.type(editor, '/ai blog: Technology trends in 2025');
      
      // Press Enter to execute command
      await user.keyboard('{Enter}');

      // Wait for AI generation
      await waitFor(() => {
        expect(mockAIService.prototype.generateContent).toHaveBeenCalledWith(
          'blog',
          'Technology trends in 2025',
          expect.any(Object)
        );
      }, { timeout: 10000 });

      // Verify content transformation
      expect(mockContentTransformer.prototype.markdownToBlocks).toHaveBeenCalledWith(
        mockAIResponse.content
      );

      // Verify editor content updated
      await waitFor(() => {
        expect(screen.getByText('AI Generated Content')).toBeInTheDocument();
      });
    });

    test('should handle AI command with parameters', async () => {
      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent=""
            onChange={jest.fn()}
          />
        </TestProviders>
      );

      // Type AI command with specific parameters
      const editor = screen.getByRole('textbox');
      await user.type(editor, '/ai article: "Sustainable Technology" tone:professional length:1000');
      await user.keyboard('{Enter}');

      await waitFor(() => {
        expect(mockAIService.prototype.generateContent).toHaveBeenCalledWith(
          'article',
          'Sustainable Technology',
          expect.objectContaining({
            tone: 'professional',
            length: 1000
          })
        );
      });
    });

    test('should generate multiple AI content types', async () => {
      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent=""
            onChange={jest.fn()}
          />
        </TestProviders>
      );

      const editor = screen.getByRole('textbox');

      // Test different content types
      const commands = [
        '/ai introduction: Welcome to our platform',
        '/ai howto: Set up development environment', 
        '/ai product: Revolutionary AI assistant',
        '/ai conclusion: Summary of key points'
      ];

      for (const command of commands) {
        await user.clear(editor);
        await user.type(editor, command);
        await user.keyboard('{Enter}');

        await waitFor(() => {
          expect(mockAIService.prototype.generateContent).toHaveBeenCalled();
        });
      }

      // Verify all content types were called
      expect(mockAIService.prototype.generateContent).toHaveBeenCalledTimes(4);
    });
  });

  describe('AI Text Enhancement', () => {
    test('should improve existing text', async () => {
      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      const initialContent = 'This text needs improvement.';

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent={initialContent}
            onChange={jest.fn()}
          />
        </TestProviders>
      );

      // Select text
      const editor = screen.getByRole('textbox');
      await user.click(editor);
      await user.keyboard('{Control>}a{/Control}');

      // Use improve command
      await user.type(editor, '/ai improve');
      await user.keyboard('{Enter}');

      await waitFor(() => {
        expect(mockAIService.prototype.generateContent).toHaveBeenCalledWith(
          'improve',
          initialContent,
          expect.any(Object)
        );
      });
    });

    test('should handle tone changes', async () => {
      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent="Casual text here"
            onChange={jest.fn()}
          />
        </TestProviders>
      );

      const editor = screen.getByRole('textbox');
      await user.click(editor);
      await user.keyboard('{Control>}a{/Control}');

      // Change tone to professional
      await user.type(editor, '/ai professional');
      await user.keyboard('{Enter}');

      await waitFor(() => {
        expect(mockAIService.prototype.generateContent).toHaveBeenCalledWith(
          'professional',
          'Casual text here',
          expect.any(Object)
        );
      });
    });

    test('should fix grammar and spelling', async () => {
      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      const textWithErrors = 'This text has gramar erors and needs fixing.';

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent={textWithErrors}
            onChange={jest.fn()}
          />
        </TestProviders>
      );

      const editor = screen.getByRole('textbox');
      await user.click(editor);
      await user.keyboard('{Control>}a{/Control}');

      await user.type(editor, '/ai fix');
      await user.keyboard('{Enter}');

      await waitFor(() => {
        expect(mockAIService.prototype.generateContent).toHaveBeenCalledWith(
          'fix',
          textWithErrors,
          expect.any(Object)
        );
      });
    });
  });

  describe('Image Integration', () => {
    test('should integrate images with AI generated content', async () => {
      // Mock image search results
      mockImageService.prototype.searchImages.mockResolvedValue([
        {
          url: 'https://images.unsplash.com/photo-tech-1',
          alt: 'Technology concept',
          attribution: 'Photo by Tech User on Unsplash'
        }
      ]);

      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent=""
            onChange={jest.fn()}
            enableImages={true}
          />
        </TestProviders>
      );

      const editor = screen.getByRole('textbox');
      await user.type(editor, '/ai blog: Technology innovations');
      await user.keyboard('{Enter}');

      await waitFor(() => {
        // Should search for relevant images
        expect(mockImageService.prototype.searchImages).toHaveBeenCalledWith(
          'Technology innovations',
          expect.any(Object)
        );
      });

      // Verify image was integrated into content
      await waitFor(() => {
        expect(screen.getByRole('img')).toBeInTheDocument();
      });
    });

    test('should handle image search failures gracefully', async () => {
      mockImageService.prototype.searchImages.mockRejectedValue(new Error('Image search failed'));

      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent=""
            onChange={jest.fn()}
            enableImages={true}
          />
        </TestProviders>
      );

      const editor = screen.getByRole('textbox');
      await user.type(editor, '/ai blog: Technology trends');
      await user.keyboard('{Enter}');

      // Should still generate content without images
      await waitFor(() => {
        expect(mockAIService.prototype.generateContent).toHaveBeenCalled();
      });

      // Should not crash or show error to user
      expect(screen.queryByText(/error/i)).not.toBeInTheDocument();
    });
  });

  describe('Error Handling & Recovery', () => {
    test('should handle AI service failures', async () => {
      mockAIService.prototype.generateContent.mockRejectedValue(new Error('AI service unavailable'));

      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent=""
            onChange={jest.fn()}
          />
        </TestProviders>
      );

      const editor = screen.getByRole('textbox');
      await user.type(editor, '/ai blog: Test content');
      await user.keyboard('{Enter}');

      // Should show error message
      await waitFor(() => {
        expect(screen.getByText(/AI service is currently unavailable/i)).toBeInTheDocument();
      });

      // Should provide retry option
      expect(screen.getByRole('button', { name: /retry/i })).toBeInTheDocument();
    });

    test('should handle rate limiting', async () => {
      mockAIService.prototype.generateContent.mockRejectedValue(new Error('Rate limit exceeded'));

      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent=""
            onChange={jest.fn()}
          />
        </TestProviders>
      );

      const editor = screen.getByRole('textbox');
      await user.type(editor, '/ai blog: Rate limit test');
      await user.keyboard('{Enter}');

      await waitFor(() => {
        expect(screen.getByText(/rate limit/i)).toBeInTheDocument();
      });
    });

    test('should handle malformed AI responses', async () => {
      mockAIService.prototype.generateContent.mockResolvedValue({
        content: null,
        images: []
      });

      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent=""
            onChange={jest.fn()}
          />
        </TestProviders>
      );

      const editor = screen.getByRole('textbox');
      await user.type(editor, '/ai blog: Malformed response test');
      await user.keyboard('{Enter}');

      await waitFor(() => {
        expect(screen.getByText(/unable to generate content/i)).toBeInTheDocument();
      });
    });
  });

  describe('Performance & User Experience', () => {
    test('should show loading state during AI generation', async () => {
      // Mock delayed response
      mockAIService.prototype.generateContent.mockImplementation(
        () => new Promise(resolve => setTimeout(() => resolve(mockAIResponse), 2000))
      );

      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent=""
            onChange={jest.fn()}
          />
        </TestProviders>
      );

      const editor = screen.getByRole('textbox');
      await user.type(editor, '/ai blog: Loading test');
      await user.keyboard('{Enter}');

      // Should show loading indicator
      await waitFor(() => {
        expect(screen.getByText(/generating content/i)).toBeInTheDocument();
      });

      // Should show progress or spinner
      expect(screen.getByRole('status')).toBeInTheDocument();
    });

    test('should handle streaming responses', async () => {
      // Mock streaming response
      const streamMock = {
        async *[Symbol.asyncIterator]() {
          yield { content: 'Partial content...' };
          yield { content: 'Partial content... more text...' };
          yield { content: 'Complete content with full text.' };
        }
      };

      mockAIService.prototype.generateContent.mockResolvedValue(streamMock as any);

      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent=""
            onChange={jest.fn()}
            enableStreaming={true}
          />
        </TestProviders>
      );

      const editor = screen.getByRole('textbox');
      await user.type(editor, '/ai blog: Streaming test');
      await user.keyboard('{Enter}');

      // Should show progressive content updates
      await waitFor(() => {
        expect(screen.getByText(/Partial content/i)).toBeInTheDocument();
      });
    });

    test('should allow cancellation of AI operations', async () => {
      // Mock long-running operation
      const mockAbortController = new AbortController();
      mockAIService.prototype.generateContent.mockImplementation(
        () => new Promise((resolve, reject) => {
          mockAbortController.signal.addEventListener('abort', () => {
            reject(new Error('Operation cancelled'));
          });
          setTimeout(() => resolve(mockAIResponse), 5000);
        })
      );

      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent=""
            onChange={jest.fn()}
          />
        </TestProviders>
      );

      const editor = screen.getByRole('textbox');
      await user.type(editor, '/ai blog: Cancellation test');
      await user.keyboard('{Enter}');

      // Wait for loading state
      await waitFor(() => {
        expect(screen.getByText(/generating content/i)).toBeInTheDocument();
      });

      // Click cancel button
      const cancelButton = screen.getByRole('button', { name: /cancel/i });
      await user.click(cancelButton);

      // Should abort the operation
      mockAbortController.abort();

      await waitFor(() => {
        expect(screen.queryByText(/generating content/i)).not.toBeInTheDocument();
      });
    });
  });

  describe('Configuration & Customization', () => {
    test('should use custom AI provider configuration', async () => {
      const customConfig = {
        provider: 'anthropic',
        model: 'claude-3-sonnet',
        temperature: 0.8
      };

      const { TestProviders } = createTestProviders();
      const user = userEvent.setup();

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent=""
            onChange={jest.fn()}
            aiConfig={customConfig}
          />
        </TestProviders>
      );

      const editor = screen.getByRole('textbox');
      await user.type(editor, '/ai blog: Custom config test');
      await user.keyboard('{Enter}');

      await waitFor(() => {
        expect(mockAIService.prototype.generateContent).toHaveBeenCalledWith(
          'blog',
          'Custom config test',
          expect.objectContaining(customConfig)
        );
      });
    });

    test('should disable AI features when not configured', async () => {
      const { TestProviders } = createTestProviders();

      render(
        <TestProviders>
          <BlockEditorWithAI 
            initialContent=""
            onChange={jest.fn()}
            enableAI={false}
          />
        </TestProviders>
      );

      // AI commands should not be available
      const editor = screen.getByRole('textbox');
      expect(editor).toBeInTheDocument();

      // Slash menu should not include AI commands
      // This would require more complex slash menu testing
      expect(true).toBe(true); // Placeholder for actual test
    });
  });
});